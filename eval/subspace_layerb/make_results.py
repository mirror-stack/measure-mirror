#!/usr/bin/env python3
"""Render RESULTS.md from the sealed run's JSON.

Every number in the document is read out of the result file, never typed.
A hand-written figure in the docs was a real defect here once (the `wilson_ci`
example said 0.7527 where the code returns 0.7533), and `test_layerb_results_
sync.py` re-derives this file to keep it that way.

    python eval/subspace_layerb/make_results.py \\
        --result eval/subspace_layerb/sealed_result.json
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CLAIM = "subspace_layerb_overfit_smallsample_balanced_20260805"
SEAL = "bd98a0450c65f35c31722477bfa3acaf0a3fc77db1b3b7112a4f4554187bbe19"
AM_SEAL = "c6a3e145e5e91ec8cc5f733b02549ec27434f4e902fa137a6e72242988569c95"


def render(d: dict) -> str:
    p, c, b, cfg = d["primary"], d["components"], d["bars"], d["config"]
    rows = [
        f"| `{n}` | {v['runs']} | {v['power']:.4f} | {v['readable']} | "
        f"{v['null_wins']} | {v['null_fpr']:.4f} |"
        for n, v in d["per_n"].items()
    ]
    withheld = ", ".join(f"n_basis={n} (rng_seed_pos {s})" for n, s in c["withheld"]) \
        or "none"
    return f"""# ㉘ layer B — sealed run for `overfit_smallsample`

**Verdict: {d['verdict']}** · claim `{CLAIM}` · seal `{SEAL[:8]}` · result `{AM_SEAL[:8]}`

> Generated by `make_results.py` from `sealed_result.json`. Do not hand-edit the
> numbers — `tests/test_layerb_results_sync.py` re-renders this file and fails
> on any drift.

## What was claimed

`BALANCED = (POWER + (1 - NULL_FPR)) / 2` — balanced accuracy over two
conditions, bar **≥ {b['balanced_min']}**, chance **{b['chance_balanced']}**.

The primary is deliberately *not* NULL_FPR alone. An **inert** instrument that
never reports a win scores a perfect `NULL_FPR = 0`; an always-on one scores
perfect power. Both land at exactly {b['chance_balanced']} here, so the vacuous
pass is unreachable by construction rather than by a side-condition someone can
forget to check. The two components are additionally hard kills on their own, so
they cannot be traded off against each other.

## Result

| | value | bar | |
|---|---|---|---|
| **BALANCED** (primary) | **{p['BALANCED']:.4f}** | ≥ {b['balanced_min']} | n = {p['n']} |
| NULL_FPR | {c['NULL_FPR']:.4f} | ≤ {b['null_fpr_max']} | {c['null_wins']} wins / {c['n_readable']} readable |
| POWER | {c['POWER']:.4f} | ≥ {b['power_min']} | {c['n_total'] - c['n_withheld']} / {c['n_total']} |

| n_basis | runs | POWER | readable | null wins | NULL_FPR |
|---|---|---|---|---|---|
{chr(10).join(rows)}

Withheld (own positive control did not fire, so the null there is unreadable and
is **not** counted as a pass): {withheld}.

## How to read NULL_FPR — the number that looks better than it is

`NULL_FPR = {c['NULL_FPR']:.4f}` sits **below** the nominal α = {b['nominal_alpha']},
and that is **not** evidence the pipeline beats its own test. Layer A's paired
sign-flip runs on {cfg['n_seeds_per_condition']} seeds with exact enumeration and
additionally requires a positive mean difference, so its attainable size is
already at or below ≈0.025. The observed rate is consistent with a correctly
calibrated test — not with a better-than-calibrated one. Reading it as the
latter would be the "too good to be true" reflex this tool exists to interrupt.

## Scope — what this does **not** close

- Synthetic **isotropic Gaussians only**; ambient dimension {cfg['ambient_dim']} only.
- One effect callback (out-of-sample R² of a linear probe). A different effect
  function is a different instrument.
- Says nothing about any real substrate.
- Does not touch layer A's standing hole: **a consistent forgery still passes**.
  Layer B produces an honest table; it cannot make layer A able to detect a
  dishonest one.

## Provenance

- Judged on rng seed block `{cfg['seed_block_start']}+`, {cfg['replications']}
  replications × {len(cfg['n_list'])} sample sizes = {p['n']} runs.
  Development seeds (module default `20260805`, test `4242`) and the pre-seal
  smoke blocks (`111000`, `222000`) were **burned** and excluded — the same
  "development signal consumed the test set" correction the layer-A arc needed.
- Protocol frozen at `COMBINED = {d['protocol_sha256']['combined']}`, verified
  bit-identical immediately before the run.
- Environment: Python {d['env']['python']}, numpy {d['env']['numpy']}.
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--result", default=str(HERE / "sealed_result.json"))
    ap.add_argument("--out", default=str(HERE / "RESULTS.md"))
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if RESULTS.md differs from a re-render")
    args = ap.parse_args()

    text = render(json.loads(Path(args.result).read_text()))
    if args.check:
        current = Path(args.out).read_text()
        if current != text:
            print("RESULTS.md is stale — re-run make_results.py")
            return 1
        print("RESULTS.md matches the sealed result")
        return 0
    Path(args.out).write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
