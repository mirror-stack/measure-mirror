#!/usr/bin/env python3
"""Render RESULTS.md from the sealed run's JSON.

Every number in the document is read out of the result file, never typed —
the same rule (and the same reason) as `eval/subspace_layerb/make_results.py`.
`tests/test_vacuous_results_sync.py` re-renders this file and fails on drift.

    python eval/subspace_vacuous_real/make_results.py
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CLAIM = "subspace_vacuous_real_runs_balanced_20260810_v2"
SEAL = "2a22a95acf542fc56f511e5f19a376883e13793cdd76da57943ac2cc157f9cf2"
AM_SEAL = "79cd081647e0c876ab89fabbd1cede56a43c40ead3f789c652db53303db19f9c"
V1_SEAL = "17c36ad65f02d408975267002f0adf280fe92f09cd567393430b039185b0cac8"
V1_AM = "1481aa28ba656916dacb68856ea3841e1a667b0c9b9434c36b247dffc684b45a"


def render(d: dict) -> str:
    p, b, cfg, a = d["primary"], d["bars"], d["config"], d["anchors"]
    rows = [
        f"| `{k}` | {v['runs']} | {v['truth']['matched']} | "
        f"{v['truth']['unmatched']} | {v['truth']['boundary']} | "
        f"[{v['margin_min']:+.4f}, {v['margin_max']:+.4f}] | "
        f"{', '.join(v['vacuous_levels'])} |"
        for k, v in d["per_condition"].items()
    ]
    return f"""# ㉘ `vacuous` — first exercise of both directions on real runs

**Verdict: {d['verdict']}** · claim `{CLAIM}` · seal `{SEAL[:8]}` · result `{AM_SEAL[:8]}`

> Generated by `make_results.py` from `sealed_result.json`. Do not hand-edit the
> numbers — `tests/test_vacuous_results_sync.py` re-renders this file and fails
> on any drift.

## What this closes, and how it was open

Finding 5 `vacuous` had never fired on anything but synthetic tables: the
FM×CDE corpus carries zero real VACUOUS labels, substrate-2 has no
matched_null arm, and the planted FN case (`vacuous_as_collapse`) hand-writes
a certificate failure into a real report (`eval/subspace_planted/RESULTS.md`
states this openly). This run replaces the hand-written direction with runs
whose certificates are **computed from their own arrays**
(`build_subspace_report(certificate_tol=…)`): the matched arm's retained
energy on the **eval split** must meet the declared target within tol.

- **honest** — k selected on the eval split (the default): margin ≥ 0 by the
  minimal-k rule; a genuinely matched arm.
- **sloppy** — k selected in-sample at small n: the shuffled basis overfits
  its fit sample and genuinely undershoots the target on the eval split.
  Matched on paper, not in fact — the vacuous illusion produced by a run
  instead of typed into one.

Cases are labelled by **ground truth** (margin recomputed from the emitted
eval-split energy cells), not by intended condition — a sloppy run where the
manipulation did not bite is scored as the matched arm it actually is (the
equivalent-mutant filter). Margins inside the boundary band
(±{cfg['boundary_delta']} around −{cfg['certificate_tol']}) are withheld.

## Result

| | value | bar | |
|---|---|---|---|
| **BALANCED_CASE** (primary) | **{p['BALANCED_CASE']:.4f}** | ≥ {b['balanced_min']} | chance {b['chance']} |
| acc on unmatched (vacuous = FAIL) | {p['acc_unmatched']:.4f} | hard | n = {p['n_unmatched']} |
| acc on matched (vacuous = OK) | {p['acc_matched']:.4f} | hard | n = {p['n_matched']} |
| withheld (boundary band) | {p['n_withheld_boundary']} | reported | |

| condition | runs | matched | unmatched | boundary | margin range | levels |
|---|---|---|---|---|---|---|
{chr(10).join(rows)}

Anchors: sloppy@8 produced no matched-class run ({a['sloppy_n8_all_unmatched']}),
honest@200 produced no unmatched-class run ({a['honest_n200_all_matched']}).
Levels seen: {', '.join(d['levels_seen'])} — the instrument is not constant.

## 🪞 The first sealed attempt went INVALID — kept, not hidden

Seal `{V1_SEAL[:8]}` (v1) demanded the positive anchor literally: *every*
sloppy@8 run in the unmatched class. One margin landed at −0.0524 — inside
the withheld band — and the anchor tripped on a run whose behaviour was
correct (certificate failed, finding FAILed). That is a clause/degenerate-state
interaction the author failed to enumerate, the exact shape
`catalog/self-catch/prereg-clause-defect-family.md` records. Handled by the
book: consumed as INVALID (am `{V1_AM[:8]}`), anchor re-stated as "no run in
the *opposite* class" (withheld cases never enter scoring, so they cannot
refute the stage), re-sealed as v2 on a **fresh seed block** with the judge
files bit-identical.

## Scope — what this does **not** close

- Synthetic isotropic Gaussians only; ambient dimension {cfg['ambient_dim']} only.
- The certificate certifies **our own run**. Layer A still cannot detect a
  consistent forgery — a stranger's hand-written `passed: true` passes.
- Ground truth is recomputed from the emitted cells, independently of the
  certificate aggregation and of layer A's consumption — but it is not an
  independent re-derivation of the energy computation itself (that is unit-
  tested, not re-derived here).
- The planted case `vacuous_as_collapse` in `eval/subspace_planted/` stays
  synthetic and stays in the set — it guards the adapter path, this run
  guards the layer-B path.

## Provenance

- Sealed seed block `{cfg['seed_block_start']}+`, {cfg['replications']}
  replications × 2 procedures × {len(cfg['n_list'])} sample sizes =
  {p['n_unmatched'] + p['n_matched'] + p['n_withheld_boundary']} runs.
  Burned blocks excluded: dev smoke `555001`, v1 attempt `1100001`.
- Protocol frozen at `COMBINED = {d['protocol_sha256']['combined']}`,
  verified bit-identical immediately before the run.
- Environment: Python {d['env']['python']}, numpy {d['env']['numpy']}.
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--result", default=str(HERE / "sealed_result.json"))
    ap.add_argument("--out", default=str(HERE / "RESULTS.md"))
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if RESULTS.md differs from a re-render")
    args = ap.parse_args()

    text = render(json.loads(Path(args.result).read_text()))
    if args.check:
        current = Path(args.out).read_text()
        if current != text:
            print("RESULTS.md is stale — re-run make_results.py")
            return 1
        print("RESULTS.md matches the sealed result")
        return 0
    Path(args.out).write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
